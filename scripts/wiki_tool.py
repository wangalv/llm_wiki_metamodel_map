def cmd_convert(v: Vault, args) -> int:
    converters = v.profile.converters()
    if args.list or not args.converter:
        if not converters:
            print(f"convert: profile '{v.profile.name}' has no converters")
        for name in sorted(converters):
            doc = (getattr(converters[name], "__doc__", "") or "").strip().splitlines()
            print(f"{name}" + (f" — {doc[0]}" if doc else ""))
        return 0 if args.list or not args.converter else 2
    fn = converters.get(args.converter)
    if fn is None:
        print(f"convert: unknown converter {args.converter!r} for profile '{v.profile.name}' "
              f"(available: {', '.join(sorted(converters)) or 'none'})", file=sys.stderr)
        return 2
    if not args.input or not args.output:
        print("convert: INPUT and --output are required", file=sys.stderr)
        return 2
    src, out = args.input.resolve(), args.output if args.output.is_absolute() else Path.cwd() / args.output
    if not src.is_file():
        print(f"convert: input not found: {args.input}", file=sys.stderr)
        return 1
    if out.exists() and not args.force:
        print(f"convert: {args.output} exists (use --force to overwrite)", file=sys.stderr)
        return 1
    out.parent.mkdir(parents=True, exist_ok=True)
    message = fn(src, out, sys.modules[__name__])
    print(message or f"convert: wrote {args.output}")
    return 0



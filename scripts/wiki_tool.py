STOPWORDS = set("""
a an and are as at be by can could do does for from has have how i if in into is it its many may
must of on or should that the their them there these this those to under was what when where
which who whom why will with would""".split())
RAW_LINK_RE = re.compile(r"\[\[\d{4}-\d{2}-\d{2}-[^\]]*\]\]")  # citations to Raw sources


def search_tokens(query: str) -> list[str]:
    """Query words minus stopwords, with simple plural folding (fees -> fee)."""
    words = [w for w in re.findall(r"[a-z0-9]+", query) if w not in STOPWORDS]
    return [w[:-1] if len(w) > 4 and w.endswith("s") and not w.endswith("ss") else w for w in words]


def note_search_text(v: Vault, rel: str) -> str:
    """Body of a compiled Wiki note, without citation links (which would match every note)."""
    if not rel or not v.abs(rel).is_file():
        return ""
    return RAW_LINK_RE.sub("", v.note(rel).body).casefold()


def cmd_search_catalog(v: Vault, args) -> int:
    path = v.abs(CATALOG)
    if not path.exists():
        print(f"search-catalog: {CATALOG} not found; run build first", file=sys.stderr)
        return 1
    try:
        rows = read_jsonl(path, CATALOG_KEYS)
    except ValueError as e:
        print(f"search-catalog: {e}", file=sys.stderr)
        return 1
    if args.tag and args.tag not in v.cfg.allowed_tags:
        print(f"search-catalog: unknown --tag {args.tag!r} (choose from {', '.join(sorted(v.cfg.allowed_tags))})",
              file=sys.stderr)
        return 2
    query = args.query.casefold().strip()
    tokens = search_tokens(query)
    if not tokens:
        print("search-catalog: query has no searchable words", file=sys.stderr)
        return 2
    needed = max(1, -(-len(tokens) // 2))  # at least half of the words must match
    results = []
    for row in rows:
        if args.tag and row.get("tag") != args.tag:
            continue
        fields = (
            (5, [row.get("title", "")]),
            (4, row.get("aliases") or []),
            (2, [row.get("tag") or "", row.get("summary") or ""]),
            (1, list(row.get("topics") or []) + [row.get("path", ""), note_search_text(v, row.get("path", ""))]),
        )
        score = matched = 0
        for tok in tokens:
            best = max((w for w, vals in fields if any(tok in str(x).casefold() for x in vals)), default=0)
            score += best
            matched += bool(best)
        if matched < needed:
            continue
        names = [str(row.get("title", "")).casefold(), *(str(a).casefold() for a in row.get("aliases") or [])]
        score += 10 if query in names else 0
        results.append((matched, score, row))
    results.sort(key=lambda r: (-r[0], -r[1], r[2]["path"]))
    results = results[:args.limit]
    if args.json:
        for _, _, row in results:
            print(json.dumps(row, ensure_ascii=False))
        return 0
    for matched, _, row in results:
        summary = f" — {row['summary']}" if row.get("summary") else ""
        print(f"[{row.get('tag')}] {row['title']}  ({row['path']}, {matched}/{len(tokens)} words){summary}")
    print(f"search-catalog: {len(results)} match(es) for {args.query!r}")
    return 0



@dataclass
class Note:
    path: str
    title: str
    text: str
    fm: dict | None
    body: str
    body_line: int
    fm_error: str | None
    kind: Kind | None = None  # the kind of the Wiki/ subfolder the note is in, if any

    @property
    def folder_tag(self) -> str | None:
        return self.kind.tag if self.kind else None


class Vault:
    def __init__(self, root: Path, cfg: Config | None = None, profile: Profile | None = None):
        self.root = root
        self.cfg = cfg or Config.load(root)
        self.profile = profile or Profile.load(root, self.cfg.profile)
        self._files: list[str] | None = None
        self._notes: dict[str, Note] = {}
        self._by_path: dict[str, str] = {}
        self._by_name: dict[str, list[str]] = {}

    def abs(self, rel: str) -> Path:
        return self.root / rel

    def files(self) -> list[str]:
        """All non-hidden files in the vault, as sorted vault-relative POSIX paths."""
        if self._files is None:
            out = []
            for dirpath, dirnames, filenames in os.walk(self.root):
                dirnames[:] = sorted(d for d in dirnames if not d.startswith(".") and d not in SKIP_DIRS)
                for name in filenames:
                    if not name.startswith("."):
                        out.append((Path(dirpath) / name).relative_to(self.root).as_posix())
            self._files = sorted(out)
            for rel in self._files:
                low = rel.lower()
                self._by_path[low] = rel
                name = rel.rsplit("/", 1)[-1]
                if name.lower().endswith(".md"):
                    self._by_path.setdefault(low[:-3], rel)
                    name = name[:-3]
                self._by_name.setdefault(name.lower(), []).append(rel)
        return self._files

    def resolve(self, target: str | None) -> str | None:
        """Resolve a wikilink target the way Obsidian does (path, else unique filename)."""
        if not target:
            return None
        self.files()
        t = target.replace("\\", "/").strip().lstrip("/")
        if "/" in t:
            return self._by_path.get(t.lower())
        hits = self._by_name.get(t.lower())
        if not hits and t.lower().endswith(".md"):
            hits = self._by_name.get(t[:-3].lower())
        return sorted(hits, key=lambda p: (p.count("/"), p))[0] if hits else None

    def note(self, rel: str) -> Note:
        if rel not in self._notes:
            text = self.abs(rel).read_text(encoding="utf-8", errors="replace")
            fm, body, body_line, err = split_frontmatter(text)
            parts = rel.split("/")
            kind = self.cfg.by_folder.get(parts[1]) if len(parts) > 2 and parts[0] == "Wiki" else None
            self._notes[rel] = Note(rel, Path(rel).stem, text, fm, body, body_line, err, kind)
        return self._notes[rel]

    def reset(self) -> None:
        """Forget cached files and notes (after build writes generated files)."""
        self._files, self._notes, self._by_path, self._by_name = None, {}, {}, {}

    def compiled_paths(self) -> list[str]:
        return [
            f for f in self.files()
            if f.endswith(".md") and f.split("/")[0] == "Wiki" and len(f.split("/")) > 2
            and f.split("/")[1] in self.cfg.by_folder and f not in self.cfg.generated_files
        ]

    def source_paths(self) -> list[str]:
        return [f for f in self.files() if f.startswith("Raw/Sources/") and f.endswith(".md")]

    def raw_file_paths(self) -> list[str]:
        return [f for f in self.files() if f.startswith("Raw/Files/")]

    def fm_link_paths(self, note: Note, key: str) -> list[str]:
        """Frontmatter wikilinks resolved to paths (unresolved entries keep their target)."""
        out = []
        for item in as_list((note.fm or {}).get(key)):
            target = link_target(item)
            if target:
                out.append(self.resolve(target) or target)
        return out


def single_tag(note: Note, allowed_tags: set[str]) -> str | None:
    tags = [t for t in as_list((note.fm or {}).get("tags")) if isinstance(t, str)]
    allowed = [t for t in tags if t in allowed_tags]
    return allowed[0] if allowed else (tags[0] if tags else None)


def coverage(v: Vault) -> dict[str, list[str]]:
    """Raw source path -> compiled knowledge notes whose `sources` cite it."""
    cov: dict[str, list[str]] = {p: [] for p in v.source_paths()}
    for np in v.compiled_paths():
        note = v.note(np)
        if note.folder_tag not in v.cfg.knowledge_tags or note.fm is None:
            continue
        for src in v.fm_link_paths(note, "sources"):
            if src in cov and np not in cov[src]:
                cov[src].append(np)
    return {k: sorted(x) for k, x in cov.items()}



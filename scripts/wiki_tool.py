def read_jsonl(path: Path, required: tuple[str, ...]) -> list[dict]:
    rows = []
    for i, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError as e:
            raise ValueError(f"{path.name} line {i}: invalid JSON ({e.msg})") from None
        if not isinstance(row, dict) or any(k not in row for k in required):
            raise ValueError(f"{path.name} line {i}: missing key(s) {[k for k in required if k not in row]}")
        rows.append(row)
    return rows


def read_manifest(v: Vault) -> dict[str, dict] | None:
    path = v.abs(MANIFEST)
    if not path.exists():
        return None
    return {row["path"]: row for row in read_jsonl(path, MANIFEST_KEYS)}


def current_entries(v: Vault, old: dict[str, dict], accept_covered: bool = False) -> list[dict]:
    cov = coverage(v)
    entries = []
    for sp in v.source_paths():
        note = v.note(sp)
        fm = note.fm or {}
        processed = fm.get("Processed") is True or (accept_covered and bool(cov[sp]))
        entry = {"path": sp, "title": str(fm.get("Title") or note.title), "processed": processed, "covered_by": cov[sp]}
        prev = old.get(sp)
        same = prev is not None and all(prev.get(k) == entry[k] for k in ("title", "processed", "covered_by"))
        entry["updated"] = prev["updated"] if same and prev.get("updated") else today()
        entries.append(entry)
    return entries


def manifest_delta(v: Vault) -> dict[str, list[str]]:
    old = read_manifest(v) or {}
    cur = {e["path"]: e for e in current_entries(v, old)}
    return {
        "new": sorted(set(cur) - set(old)),
        "removed": sorted(set(old) - set(cur)),
        "changed": sorted(p for p in set(cur) & set(old)
                          if any(cur[p][k] != old[p].get(k) for k in ("title", "processed", "covered_by"))),
    }


def set_processed_true(path: Path) -> bool:
    with open(path, encoding="utf-8", newline="") as fh:
        text = fh.read()
    m = re.match(r"\ufeff?---\r?\n(.*?)\r?\n(?:---|\.\.\.)[ \t]*(?:\r?\n|$)", text, re.S)
    if not m:
        return False
    new_fm, n = re.subn(r"(?m)^Processed:[ \t]*false[ \t]*(?=\r?$)", "Processed: true", m.group(1))
    if n != 1:
        return False
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(text[:m.start(1)] + new_fm + text[m.end(1):])
    return True


def cmd_source_scan(v: Vault, args) -> int:
    if args.accept_covered and not args.update:
        print("source-scan: --accept-covered requires --update", file=sys.stderr)
        return 2
    try:
        old = read_manifest(v) or {}
    except ValueError as e:
        print(f"source-scan: {e}", file=sys.stderr)
        return 1
    entries = current_entries(v, old, accept_covered=args.accept_covered)

    if args.json:
        for e in entries:
            print(json.dumps(e, ensure_ascii=False))
    else:
        for e in entries:
            state = "new" if e["path"] not in old else (
                "changed" if any(old[e["path"]].get(k) != e[k] for k in ("title", "processed", "covered_by")) else "ok")
            print(f"{'P' if e['processed'] else '-'} covered:{len(e['covered_by'])} manifest:{state:7} {e['path']}  ({e['title']})")
        print(f"source-scan: {len(entries)} source(s), {sum(e['processed'] for e in entries)} processed, "
              f"{sum(bool(e['covered_by']) for e in entries)} covered")

    if not args.update:
        return 0
    if args.accept_covered:
        for e in entries:
            note = v.note(e["path"])
            if e["covered_by"] and (note.fm or {}).get("Processed") is not True:
                if set_processed_true(v.abs(e["path"])):
                    print(f"marked Processed: true  {e['path']}")
                else:
                    print(f"warning: could not set Processed in {e['path']} (expected 'Processed: false')", file=sys.stderr)
    content = "".join(json.dumps(e, ensure_ascii=False) + "\n" for e in entries)
    path = v.abs(MANIFEST)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        print(f"{MANIFEST} unchanged")
    else:
        path.write_text(content, encoding="utf-8")
        print(f"wrote {MANIFEST} ({len(entries)} entries)")
    return 0



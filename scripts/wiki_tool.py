LOG_HEADER = (
    "# Wiki Log\n\n"
    "Append-only activity log. Add entries with "
    "`python3 scripts/wiki_tool.py log --title \"...\" --details \"...\"`.\n"
)


def cmd_log(v: Vault, args) -> int:
    title = " ".join(args.title.split())
    if not title:
        print("log: --title must not be empty", file=sys.stderr)
        return 2
    path = v.abs(WIKI_LOG)
    existing = path.read_text(encoding="utf-8") if path.exists() else LOG_HEADER
    if not existing.endswith("\n"):
        existing += "\n"
    stamp = dt.datetime.now().strftime("%Y-%m-%d %H:%M")
    entry = f"\n## [{stamp}] {title}\n"
    if args.details.strip():
        entry += f"\n{args.details.strip()}\n"
    path.write_text(existing + entry, encoding="utf-8")
    print(f"appended to {WIKI_LOG}: [{stamp}] {title}")
    return 0



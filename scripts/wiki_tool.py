def cmd_doctor(v: Vault, args) -> int:
    results: list[tuple[str, str]] = []
    ok = lambda msg: results.append(("OK", msg))
    warn = lambda msg: results.append(("WARN", msg))
    fail = lambda msg: results.append(("FAIL", msg))

    version = ".".join(map(str, sys.version_info[:3]))
    (ok if sys.version_info >= MIN_PYTHON else fail)(f"Python {version} (need >= {'.'.join(map(str, MIN_PYTHON))})")
    rules = f", {len(v.cfg.rules)} rules" if v.cfg.rules else ""
    rules += f", {len(v.cfg.generators)} generators" if v.cfg.generators else ""
    ok(f"config: {v.cfg.origin} ({len(v.cfg.kinds)} kinds: {', '.join(k.tag for k in v.cfg.kinds)}{rules})")
    ok(v.profile.describe())

    missing = [d for d in v.cfg.required_dirs if not v.abs(d).is_dir()]
    if missing:
        fail(f"missing folder(s): {', '.join(missing)}")
    else:
        ok(f"all {len(v.cfg.required_dirs)} required folders present")
    (ok if v.abs("AGENTS.md").is_file() else warn)("AGENTS.md " + ("present" if v.abs("AGENTS.md").is_file() else "missing"))

    compiled = v.compiled_paths()
    cat = v.abs(CATALOG)
    if not cat.exists():
        warn(f"{CATALOG} missing; run build")
    else:
        try:
            rows = read_jsonl(cat, CATALOG_KEYS)
        except ValueError as e:
            fail(f"{CATALOG}: {e}")
        else:
            stale = stale_outputs(v)
            msg = f"{CATALOG}: {len(rows)} entries for {len(compiled)} compiled notes"
            (warn if stale else ok)(msg + (f"; {len(stale)} generated file(s) stale, run build" if stale else ", up to date"))

    try:
        manifest = read_manifest(v)
    except ValueError as e:
        fail(f"{MANIFEST}: {e}")
    else:
        if manifest is None:
            warn(f"{MANIFEST} missing; run source-scan --update")
        else:
            delta = manifest_delta(v)
            n = sum(map(len, delta.values()))
            (warn if n else ok)(f"{MANIFEST}: {len(manifest)} entries" +
                                (f"; {n} out of date, run source-delta" if n else ", up to date"))

    cov = coverage(v)
    sources = v.source_paths()
    processed = sum((v.note(p).fm or {}).get("Processed") is True for p in sources)
    ok(f"Raw: {len(sources)} source note(s), {processed} processed, {sum(bool(c) for c in cov.values())} covered; "
       f"{len(v.raw_file_paths())} attachment(s)")
    counts = {k.tag: 0 for k in v.cfg.kinds}
    for p in compiled:
        counts[v.note(p).folder_tag] += 1
    ok("Wiki: " + ", ".join(f"{n} {tag}" for tag, n in counts.items()))
    broken = [p for p in compiled + sources if v.note(p).fm_error]
    if broken:
        warn(f"{len(broken)} note(s) with missing/invalid frontmatter (run lint / source-lint)")

    try:
        hooks = subprocess.run(["git", "-C", str(v.root), "config", "--get", "core.hooksPath"],
                               capture_output=True, text=True, timeout=10).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        hooks = None
    if hooks is None:
        warn("git not available; cannot check hooks")
    elif hooks.endswith(".githooks"):
        ok(f"git hooks installed (core.hooksPath = {hooks})")
    else:
        warn("git hooks not installed; run scripts/install_hooks.sh")

    for status, msg in results:
        print(f"{status:4}  {msg}")
    failed = sum(s == "FAIL" for s, _ in results)
    print(f"doctor: {'FAILED' if failed else 'healthy'} ({failed} failure(s), {sum(s == 'WARN' for s, _ in results)} warning(s))")
    return 1 if failed else 0



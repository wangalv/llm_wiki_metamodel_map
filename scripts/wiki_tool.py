def gen_heading_index(v, gen) -> str:
    p = gen.params
    sources = _selected_sources(v, p["sources"])
    lo, hi = p["levels"]
    body = []
    for src in sources:
        note = v.note(src)
        title = str((note.fm or {}).get("Title") or note.title)
        if len(sources) > 1:
            body += [f"## {title}", ""]
        for sec in source_sections(note):
            if not lo <= sec.level <= hi:
                continue
            if (p["heading"] and not p["heading"].search(sec.title)) or (p["exclude"] and p["exclude"].search(sec.title)):
                continue
            label = sec.title.replace("|", "-").replace("[", "(").replace("]", ")")
            body.append("  " * (sec.level - lo) + f"- {_src_link(src, sec.title, label)}")
        body.append("")
    names = ", ".join(str((v.note(s).fm or {}).get("Title") or v.note(s).title) for s in sources) or "no sources"
    dates = [(v.note(s).fm or {}).get("Created") for s in sources]
    return _render_generated(v, gen, f"Outline of {names}", f"The heading structure of {names}, linked to each section.",
                             body or ["_No headings matched._", ""], sources, _latest_date(dates))


def gen_term_list(v, gen) -> str:
    p = gen.params
    sources = _selected_sources(v, p["sources"])
    body, count = [], 0
    for src in sources:
        note = v.note(src)
        scopes = [(s.title, s.text) for s in source_sections(note) if p["section"] and p["section"].search(s.title)]
        if not p["section"]:
            scopes = [("", note.body)]
        for anchor, text in scopes:
            paras = [x for x in re.split(r"\n\s*\n", text) if x.strip()]
            entries: list[tuple[str, list[str]]] = []
            for para in paras:
                m = p["term"].search(para.strip().split("\n")[0])
                if m:
                    entries.append((m.group(1).strip(), [para.strip()]))
                elif entries and not LEVEL_HEADING_RE.match(para.strip()):
                    entries[-1][1].append(para.strip())
            for term, parts in entries:
                count += 1
                label = anchor or (note.fm or {}).get("Title") or note.title
                body += [f"### {term}", "", f"> [!{p['callout']}] {_src_link(src, anchor, str(label))}"]
                for part in parts:
                    body += [f"> {line}" if line.strip() else ">" for line in part.split("\n")] + [">"]
                body[-1:] = [""]
    names = ", ".join(str((v.note(s).fm or {}).get("Title") or v.note(s).title) for s in sources) or "no sources"
    dates = [(v.note(s).fm or {}).get("Created") for s in sources]
    return _render_generated(v, gen, f"Terms in {names}", f"{count} terms defined in {names}, quoted from the source.",
                             body or ["_No terms matched._", ""], sources, _latest_date(dates))


def _cell_value(v, entry: dict, fm: dict, col: str) -> str:
    if col == "note":
        return _link(entry["path"], entry["title"], in_table=True)
    if col in ("summary", "tag", "path"):
        return _cell(entry.get(col))
    if col == "links":
        return ", ".join(_link(x, Path(x).stem, in_table=True) for x in entry["links"])
    if col in ("topics", "sources"):
        return ", ".join(_link(x, Path(x).stem, in_table=True) if x.endswith(".md") else _cell(x) for x in entry[col])
    value = (entry.get("fields") or {}).get(col, fm.get(col))
    if isinstance(value, list):
        return ", ".join(_link(x, Path(x).stem, in_table=True) if isinstance(x, str) and x.endswith(".md") and "/" in x
                         else _cell(x) for x in value)
    if isinstance(value, str) and value.endswith(".md") and "/" in value:
        return _link(value, Path(value).stem, in_table=True)
    return _cell(value)


def _sort_key(entry: dict, fm: dict, col: str):
    value = entry.get(col) if col in entry else (entry.get("fields") or {}).get(col, fm.get(col))
    if isinstance(value, list):
        value = ", ".join(map(str, value))
    return (value is None, str(value if value is not None else "").casefold())


def gen_catalog_table(v, gen) -> str:
    p = gen.params
    own = set(v.cfg.generator_outputs)
    rows = []
    for rel in v.compiled_paths():
        n = v.note(rel)
        if rel in own or n.fm is None or n.folder_tag not in p["kinds"]:
            continue
        if not where_matches(n.fm, p["where"]):
            continue
        rows.append((catalog_entry(v, n), n.fm))
    for col in reversed(p["sort"] or ("title",)):
        rows.sort(key=lambda r: _sort_key(r[0], r[1], col))
    header = ["| " + " | ".join(c for c in p["columns"]) + " |", "|" + "---|" * len(p["columns"])]
    groups: dict[str, list] = {}
    for entry, fm in rows:
        key = str(_cell_value(v, entry, fm, p["group_by"])) if p["group_by"] else ""
        groups.setdefault(key, []).append((entry, fm))
    body = []
    for key in sorted(groups, key=str.casefold):
        if p["group_by"]:
            body += [f"## {key or '(none)'}", ""]
        body += header + ["| " + " | ".join(_cell_value(v, e, fm, c) for c in p["columns"]) + " |"
                          for e, fm in groups[key]] + [""]
    kinds = ", ".join(p["kinds"])
    return _render_generated(v, gen, f"Table of {kinds} notes", f"{len(rows)} notes of kind {kinds}.",
                             body or ["_No notes matched._", ""], [],
                             _latest_date(e["updated"] for e, _ in rows))


def _bases_filter(key: str, value) -> str:
    rhs = ("true" if value else "false") if isinstance(value, bool) else (
        str(value) if isinstance(value, int) else json.dumps(value, ensure_ascii=False))
    return f"'{key} == {rhs}'" if "'" not in rhs else json.dumps(f"{key} == {rhs}")


def gen_bases_view(v, gen) -> str:
    p = gen.params
    folders = [f'file.inFolder("Wiki/{v.cfg.by_tag[t].folder}")' for t in p["kinds"]]
    lines = [f"# {GENERATED_CONFIG_NOTICE.format(id=gen.id)[5:-4]}", "filters:", "  and:"]
    if len(folders) == 1:
        lines.append(f"    - '{folders[0]}'")
    else:
        lines += ["    - or:"] + [f"        - '{f}'" for f in folders]
    lines += [f"    - {_bases_filter(k, x)}" for k, x in p["where"].items()]
    lines.append("views:")
    for view in p["views"]:
        lines += [f"  - type: {view['type']}", f"    name: {json.dumps(view['name'], ensure_ascii=False)}"]
        if view["where"]:
            lines += ["    filters:", "      and:"] + [f"        - {_bases_filter(k, x)}" for k, x in view["where"].items()]
        if view["group_by"]:
            lines += ["    groupBy:", f"      property: {view['group_by']}", "      direction: ASC"]
        lines.append("    order:")
        lines += [f"      - {'file.name' if c == 'note' else c}" for c in view["columns"]]
    return "\n".join(lines) + "\n"


GENERATOR_RUNNERS = {
    "heading_index": gen_heading_index,
    "term_list": gen_term_list,
    "catalog_table": gen_catalog_table,
    "bases_view": gen_bases_view,
}


def config_generator_outputs(v: "Vault", phase: str) -> dict[str, str]:
    """Outputs of the configured generators. Phase 'sources' runs everything except catalog_table,
    phase 'notes' runs catalog_table (it reads other notes, so it runs after the others are written)."""
    out = {}
    for gen in v.cfg.generators:
        if (gen.type == "catalog_table") == (phase == "notes"):
            out[gen.output] = GENERATOR_RUNNERS[gen.type](v, gen)
    return out



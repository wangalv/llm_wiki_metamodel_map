KEY_RE = re.compile(r"^([A-Za-z_][\w-]*)[ \t]*:(?:[ \t]+(.*)|[ \t]*)$")
ITEM_RE = re.compile(r"^[ \t]*-(?:[ \t]+(.*)|[ \t]*)$")


def _parse_quoted(s: str) -> tuple[str, str]:
    """Parse a quoted scalar at the start of s; return (value, remainder)."""
    quote, out, i = s[0], [], 1
    while i < len(s):
        c = s[i]
        if quote == '"' and c == "\\" and i + 1 < len(s):
            out.append({"n": "\n", "t": "\t"}.get(s[i + 1], s[i + 1]))
            i += 2
            continue
        if c == quote:
            if quote == "'" and s[i + 1:i + 2] == "'":
                out.append("'")
                i += 2
                continue
            return "".join(out), s[i + 1:]
        out.append(c)
        i += 1
    raise ValueError(f"unterminated quote in {s!r}")


def _check_trailing(rest: str, context: str) -> None:
    rest = rest.strip()
    if rest and not rest.startswith("#"):
        raise ValueError(f"unexpected text after {context}: {rest!r}")


def _parse_plain(s: str):
    low = s.lower()
    if low == "true":
        return True
    if low == "false":
        return False
    if low in ("null", "~", ""):
        return None
    if re.fullmatch(r"[-+]?\d+", s):
        return int(s)
    return s


def _parse_flow_list(s: str) -> list:
    if s.startswith("[["):
        raise ValueError("wikilinks in frontmatter must be quoted, e.g. \"[[Note]]\"")
    items, buf, i = [], "", 1
    while i < len(s):
        c = s[i]
        if c in "\"'" and not buf.strip():
            value, rest = _parse_quoted(s[i:])
            items.append(value)
            buf = "\0"  # marks a finished quoted item
            i = len(s) - len(rest)
            continue
        if c in ",]":
            if buf != "\0" and buf.strip():
                items.append(_parse_plain(buf.strip()))
            elif buf != "\0" and c == "," :
                raise ValueError(f"empty item in {s!r}")
            buf = ""
            if c == "]":
                _check_trailing(s[i + 1:], "list")
                return items
        else:
            if buf == "\0":
                if not c.isspace():
                    raise ValueError(f"unexpected text after quoted item in {s!r}")
            else:
                buf += c
        i += 1
    raise ValueError(f"unterminated list {s!r}")


def parse_scalar(raw: str | None):
    s = (raw or "").strip()
    if not s or s.startswith("#"):
        return None
    if s[0] in "\"'":
        value, rest = _parse_quoted(s)
        _check_trailing(rest, "quoted value")
        return value
    if s.startswith("["):
        return _parse_flow_list(s)
    if s.startswith("{"):
        raise ValueError("inline mappings are not supported")
    return _parse_plain(re.split(r"\s+#", s, maxsplit=1)[0].strip())


def parse_yaml(lines: list[str]) -> dict:
    data: dict = {}
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip() or line.lstrip().startswith("#"):
            i += 1
            continue
        if line[0] in " \t":
            raise ValueError(f"line {i + 1}: unexpected indentation")
        m = KEY_RE.match(line)
        if not m:
            raise ValueError(f"line {i + 1}: expected 'key: value'")
        key, raw = m.group(1), m.group(2)
        if key in data:
            raise ValueError(f"line {i + 1}: duplicate key '{key}'")
        i += 1
        if raw is None or not raw.strip() or raw.strip().startswith("#"):
            items = []
            while i < len(lines):
                nxt = lines[i]
                if not nxt.strip() or nxt.lstrip().startswith("#"):
                    i += 1
                    continue
                im = ITEM_RE.match(nxt)
                if not im:
                    if nxt[0] in " \t":
                        raise ValueError(f"line {i + 1}: nested mappings are not supported")
                    break
                items.append(parse_scalar(im.group(1)))
                i += 1
            data[key] = items if items else None
        else:
            data[key] = parse_scalar(raw)
    return data


def split_frontmatter(text: str) -> tuple[dict | None, str, int, str | None]:
    """Return (frontmatter, body, body_start_line, error)."""
    text = text.lstrip("\ufeff")
    lines = text.split("\n")
    if lines[0].rstrip("\r") != "---":
        return None, text, 1, "missing frontmatter"
    for j in range(1, len(lines)):
        if lines[j].rstrip("\r") in ("---", "..."):
            body = "\n".join(lines[j + 1:])
            try:
                return parse_yaml([ln.rstrip("\r") for ln in lines[1:j]]), body, j + 2, None
            except ValueError as e:
                return None, body, j + 2, f"invalid frontmatter: {e}"
    return None, text, 1, "unterminated frontmatter"


def as_list(value) -> list:
    if value is None:
        return []
    return value if isinstance(value, list) else [value]



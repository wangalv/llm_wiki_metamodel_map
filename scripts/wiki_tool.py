def lint_compiled(v: Vault) -> list[Finding]:
    out: list[Finding] = []
    add = lambda lvl, code, path, msg, line=None: out.append(Finding(lvl, code, path, msg, line))
    cfg = v.cfg
    compiled = v.compiled_paths()
    compiled_set = set(compiled)
    sources_set = set(v.source_paths())
    inbound: dict[str, set[str]] = {p: set() for p in compiled}
    names: dict[str, set[str]] = {}

    for p in compiled:
        n = v.note(p)
        if n.fm_error:
            add("error", "F1", p, n.fm_error)
            continue
        fm = n.fm or {}
        missing = [k for k in cfg.compiled_fields if k not in fm]
        missing += [f.name for f in n.kind.fields if f.required is True and f.name not in fm]
        if missing:
            add("error", "F2", p, f"missing field(s): {', '.join(missing)}")
        absent = [f.name for f in n.kind.fields if f.required == "recommended" and f.name not in fm]
        if absent:
            add("warn", "F2", p, f"missing recommended field(s): {', '.join(absent)}")
        for spec in n.kind.fields:
            for err in field_errors(v, spec, fm.get(spec.name)):
                add("error", "F9", p, f"field '{spec.name}': {err}")

        tags = as_list(fm.get("tags"))
        if len(tags) != 1 or tags[0] not in cfg.allowed_tags:
            add("error", "F3", p, f"tags must be exactly one of {sorted(cfg.allowed_tags)}, got {tags}")
        elif tags[0] != n.folder_tag:
            add("error", "F3", p, f"tag '{tags[0]}' does not match folder (expected '{n.folder_tag}')")

        sources = as_list(fm.get("sources"))
        count = fm.get("source_count")
        if "source_count" in fm and (not isinstance(count, int) or isinstance(count, bool) or count != len(sources)):
            add("error", "F4", p, f"source_count is {count!r} but sources lists {len(sources)}")

        for key in ("created", "updated"):
            if key in fm and not is_date(fm.get(key)):
                add("error", "F5", p, f"{key} must be YYYY-MM-DD, got {fm.get(key)!r}")
        if is_date(fm.get("created")) and is_date(fm.get("updated")) and fm["updated"] < fm["created"]:
            add("error", "F5", p, "updated is earlier than created")

        if "status" in fm and fm.get("status") not in cfg.statuses:
            add("error", "F6", p, f"status must be one of {list(cfg.statuses)}, got {fm.get('status')!r}")

        summary = summarize(n.body)
        if n.kind.summary:
            if not summary:
                add("warn", "F7", p, "no one-sentence summary after the # heading")
            elif len(summary) > 200:
                add("warn", "F7", p, f"summary is {len(summary)} characters (max 200)")

        for item in as_list(fm.get("topics")):
            r = v.resolve(link_target(item))
            if not (r and r.startswith(f"Wiki/{cfg.topics_folder}/") and r in compiled_set):
                add("error", "F8", p, f"topics entry {item!r} does not resolve to a note in Wiki/{cfg.topics_folder}/")
            elif r != p:
                inbound[r].add(p)

        # Sources and citations
        if n.kind.requires_sources and not sources:
            add("error", "S1", p, "no sources; compiled notes must cite at least one Raw source")
        listed = set()
        for item in sources:
            r = v.resolve(link_target(item))
            if not (r and r in sources_set):
                add("error", "S2", p, f"source {item!r} does not resolve to a file in Raw/Sources/")
            else:
                listed.add(r)

        cited = set()
        for link in body_links(n.body, n.body_line):
            r = v.resolve(link.target)
            if r is None:
                add("error", "L1", p, f"broken link [[{link.target}]]", link.line)
                continue
            if r in sources_set:
                cited.add(r)
                if link.anchor:
                    anchor = link.anchor.split("#")[-1].strip()
                    src_text = v.note(r).text
                    ok = (f"^{anchor[1:]}" in src_text) if anchor.startswith("^") else \
                        " ".join(anchor.split()).casefold() in headings(src_text)
                    if not ok:
                        add("error", "S3", p, f"[[{link.target}#{link.anchor}]]: no such heading/block in source", link.line)
                if r not in listed:
                    add("error", "S4", p, f"cites [[{link.target}]] but it is not listed in sources", link.line)
            if r in compiled_set and r != p:
                inbound[r].add(p)
        if n.kind.requires_sources:
            for r in sorted(listed - cited):
                add("warn", "S5", p, f"source {Path(r).stem} is listed but never cited in the body")

        # Naming
        if set(n.title) & FORBIDDEN_NAME_CHARS:
            add("error", "N2", p, "filename contains a forbidden character")
        if n.kind.name == "date" and not is_date(n.title):
            add("error", "N3", p, f"{n.kind.tag} notes must be named YYYY-MM-DD.md")
        for name in [n.title, *[str(a) for a in as_list(fm.get("aliases")) if a]]:
            names.setdefault(name.casefold(), set()).add(p)

        # Content
        if any(ph in n.text for ph in cfg.placeholders):
            add("warn", "C2", p, "template placeholder left in note")
        if fm.get("status") == "stable" and "[!question]" in n.body:
            add("warn", "C3", p, "status is stable but the note has an open [!question]")

    for p in compiled:
        if v.note(p).kind.orphan_check and not inbound[p] and not v.note(p).fm_error:
            add("warn", "L3", p, "orphan: no other Wiki note links here")

    stems: dict[str, list[str]] = {}
    for f in v.files():
        if f.endswith(".md"):
            stems.setdefault(Path(f).stem.casefold(), []).append(f)
    for paths in stems.values():
        if len(paths) > 1:
            add("error", "L2", paths[0], f"filename is not unique in the vault: {', '.join(paths)}")

    reported = set()
    for key, paths in names.items():
        if len(paths) > 1 and frozenset(paths) not in reported:
            reported.add(frozenset(paths))
            add("warn", "N4", sorted(paths)[0], f"possible duplicates share the name/alias '{key}': {', '.join(sorted(paths))}")

    for f in v.files():
        if f.startswith("Wiki/") and f.count("/") == 1 and f.endswith(".md") and f not in cfg.system_files:
            add("warn", "L5", f, "compiled notes belong in a Wiki/ subfolder")

    for rel in stale_outputs(v):
        add("error", "K1", rel, "generated file is out of date; run build")
    for rel in stale_schema_outputs(v):
        add("error", "K5", rel, "out of date with Schema/wiki-config.json; run sync-schema")
    for rel in git_ignored(v, [f for f in v.files() if f.startswith("Wiki/")]):
        add("error", "K4", rel, "ignored by .gitignore, so it would never be committed")
    run_config_rules(v, add)
    run_profile_rules(v, "compiled_rules", add)
    return out


def run_profile_rules(v: Vault, hook: str, add) -> None:
    """Run the profile's rules.<hook>(v, add, core), if it has one."""
    fn = v.profile.hook("rules", hook)
    if fn:
        fn(v, add, sys.modules[__name__])



@dataclass(frozen=True)
class FieldSpec:
    """A typed frontmatter field declared in wiki-config.json."""
    name: str
    type: str                         # string | int | bool | date | link | list
    required: object = False          # True | "recommended" | False
    enum: tuple | None = None
    pattern: object = None            # compiled regex or None
    to_kind: str | None = None        # link target: a kind tag, or "source" for Raw/Sources notes
    item: str | None = None           # item type for lists
    template: object = _NO_TEMPLATE   # value written into generated templates
    description: str = ""

    def describe_type(self) -> str:
        if self.type == "list":
            item = self.item or "string"
            return f"list of {item}s" + (f" → {self.to_kind}" if item == "link" and self.to_kind else "")
        return self.type + (f" → {self.to_kind}" if self.type == "link" and self.to_kind else "")

    def describe_values(self) -> str:
        if self.enum:
            return ", ".join(f"`{x}`" for x in self.enum)
        if self.pattern is not None:
            return f"matches `{self.pattern.pattern}`"
        return ""


def parse_field_spec(name: str, raw, where: str) -> FieldSpec:
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_-]*", name):
        raise ConfigError(f"{where}: invalid field name {name!r}")
    if not isinstance(raw, dict):
        raise ConfigError(f"{where}.{name}: must be an object")
    bad = sorted(set(raw) - FIELD_SPEC_KEYS)
    if bad:
        raise ConfigError(f"{where}.{name}: unknown key(s): {', '.join(bad)}")
    ftype = raw.get("type")
    if ftype not in FIELD_TYPES:
        raise ConfigError(f"{where}.{name}: 'type' must be one of {', '.join(FIELD_TYPES)}")
    required = raw.get("required", False)
    if required not in (True, False, "recommended"):
        raise ConfigError(f"{where}.{name}: 'required' must be true, false or \"recommended\"")
    item = raw.get("item")
    if ftype == "list":
        item = item or "string"
        if item not in LIST_ITEM_TYPES:
            raise ConfigError(f"{where}.{name}: 'item' must be one of {', '.join(LIST_ITEM_TYPES)}")
    elif item is not None:
        raise ConfigError(f"{where}.{name}: 'item' only applies to lists")
    base = item if ftype == "list" else ftype
    enum = raw.get("enum")
    if enum is not None:
        if base not in ("string", "int") or not isinstance(enum, list) or not enum:
            raise ConfigError(f"{where}.{name}: 'enum' needs a non-empty list on a string or int field")
        enum = tuple(enum)
    pattern = raw.get("pattern")
    if pattern is not None:
        if base != "string" or not isinstance(pattern, str):
            raise ConfigError(f"{where}.{name}: 'pattern' only applies to string fields")
        try:
            pattern = re.compile(pattern)
        except re.error as e:
            raise ConfigError(f"{where}.{name}: 'pattern' is not a valid regex: {e}") from None
    to_kind = raw.get("to_kind")
    if to_kind is not None and base != "link":
        raise ConfigError(f"{where}.{name}: 'to_kind' only applies to link fields")
    spec = FieldSpec(name, ftype, required, enum, pattern, to_kind, item,
                     raw.get("template", _NO_TEMPLATE), str(raw.get("description", "")))
    if spec.template is not _NO_TEMPLATE and field_errors(None, spec, spec.template, check_links=False):
        raise ConfigError(f"{where}.{name}: 'template' value does not match the field type")
    return spec


def _value_error(spec: FieldSpec, base: str, value, v, check_links: bool) -> str | None:
    """Why `value` is not a valid `base`-typed value for `spec`, or None if it is."""
    if base == "string":
        if not isinstance(value, str):
            return f"expected a string, got {value!r}"
        if spec.enum and value not in spec.enum:
            return f"must be one of {list(spec.enum)}, got {value!r}"
        if spec.pattern is not None and not spec.pattern.search(value):
            return f"{value!r} does not match {spec.pattern.pattern!r}"
    elif base == "int":
        if not isinstance(value, int) or isinstance(value, bool):
            return f"expected an integer, got {value!r}"
        if spec.enum and value not in spec.enum:
            return f"must be one of {list(spec.enum)}, got {value!r}"
    elif base == "bool":
        if not isinstance(value, bool):
            return f"expected true or false, got {value!r}"
    elif base == "date":
        if not is_date(value):
            return f"expected YYYY-MM-DD, got {value!r}"
    elif base == "link":
        if not isinstance(value, str) or not value.strip():
            return f"expected a wikilink, got {value!r}"
        if check_links:
            r = v.resolve(link_target(value))
            if r is None:
                return f"{value!r} does not resolve to a file"
            if spec.to_kind == "source" and r not in set(v.source_paths()):
                return f"{value!r} is not a note in Raw/Sources/"
            if spec.to_kind and spec.to_kind != "source":
                folder = v.cfg.by_tag[spec.to_kind].folder
                if not r.startswith(f"Wiki/{folder}/"):
                    return f"{value!r} is not a note of kind '{spec.to_kind}' (Wiki/{folder}/)"
    return None


def field_errors(v, spec: FieldSpec, value, check_links: bool = True) -> list[str]:
    """Type errors for one frontmatter value. Absent/empty (None) values are not checked here."""
    if value is None:
        return []
    if spec.type == "list":
        if not isinstance(value, list):
            return [f"expected a list, got {value!r}"]
        errs = [_value_error(spec, spec.item or "string", x, v, check_links) for x in value]
        return [e for e in errs if e]
    err = _value_error(spec, spec.type, value, v, check_links)
    return [err] if err else []


def field_catalog_value(v, spec: FieldSpec, value):
    """A frontmatter value as stored in the catalog: links resolved to vault paths."""
    if value is None:
        return None
    if spec.type == "link" or (spec.type == "list" and spec.item == "link"):
        items = value if isinstance(value, list) else [value]
        resolved = [v.resolve(link_target(x)) or link_target(x) for x in items if isinstance(x, str)]
        return resolved if spec.type == "list" else (resolved[0] if resolved else None)
    return value


def _str_list(data: dict, key: str) -> tuple[str, ...]:
    value = data[key]
    if not isinstance(value, list) or not all(isinstance(x, str) and x for x in value):
        raise ConfigError(f"'{key}' must be a list of non-empty strings")
    return tuple(value)


class Config:
    """Vault configuration: built-in defaults overridden by Schema/wiki-config.json."""

    def __init__(self, data: dict, origin: str):
        self.origin = origin
        unknown = sorted(k for k in data if k not in DEFAULT_CONFIG and not k.startswith("_"))
        if unknown:
            raise ConfigError(f"unknown key(s): {', '.join(unknown)}")
        merged = {**DEFAULT_CONFIG, **{k: v for k, v in data.items() if not k.startswith("_")}}
        if merged["version"] != 1:
            raise ConfigError(f"unsupported version {merged['version']!r} (expected 1)")
        if not isinstance(merged["profile"], str) or not re.fullmatch(r"[a-z][a-z0-9_-]*", merged["profile"]):
            raise ConfigError("'profile' must be a lowercase name like 'default' or 'legislation'")
        self.profile = merged["profile"]

        if not isinstance(merged["kinds"], list) or not merged["kinds"]:
            raise ConfigError("'kinds' must be a non-empty list")
        kinds = []
        for i, raw in enumerate(merged["kinds"]):
            if not isinstance(raw, dict):
                raise ConfigError(f"kinds[{i}] must be an object")
            bad = sorted(set(raw) - {"tag", "folder", *KIND_DEFAULTS})
            if bad:
                raise ConfigError(f"kinds[{i}]: unknown key(s): {', '.join(bad)}")
            k = {**KIND_DEFAULTS, **raw}
            if not re.fullmatch(r"[a-z][a-z0-9-]*", str(k.get("tag", ""))) or k["tag"] == "source":
                raise ConfigError(f"kinds[{i}]: 'tag' must be a lowercase word other than 'source'")
            if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9 _-]*", str(k.get("folder", ""))):
                raise ConfigError(f"kinds[{i}]: 'folder' must be a single folder name under Wiki/")
            for flag in ("requires_sources", "summary", "orphan_check"):
                if not isinstance(k[flag], bool):
                    raise ConfigError(f"kinds[{i}]: '{flag}' must be true or false")
            if k["name"] not in ("title", "date"):
                raise ConfigError(f"kinds[{i}]: 'name' must be 'title' or 'date'")
            if k["index_order"] not in ("asc", "desc"):
                raise ConfigError(f"kinds[{i}]: 'index_order' must be 'asc' or 'desc'")
            if not isinstance(k["fields"], dict):
                raise ConfigError(f"kinds[{i}]: 'fields' must be an object")
            fields = tuple(parse_field_spec(n, spec, f"kinds[{i}].fields") for n, spec in k["fields"].items())
            kinds.append(Kind(k["tag"], k["folder"], k["requires_sources"], k["summary"],
                              k["orphan_check"], k["name"], k["index_order"], fields))
        for attr in ("tag", "folder"):
            values = [getattr(k, attr) for k in kinds]
            dup = sorted({x for x in values if values.count(x) > 1})
            if dup:
                raise ConfigError(f"duplicate kind {attr}(s): {', '.join(dup)}")
        self.kinds: tuple[Kind, ...] = tuple(kinds)
        self.by_folder = {k.folder: k for k in kinds}
        self.by_tag = {k.tag: k for k in kinds}
        self.allowed_tags = set(self.by_tag)
        self.knowledge_tags = {k.tag for k in kinds if k.requires_sources}

        if merged["topics_kind"] not in self.by_tag:
            raise ConfigError(f"'topics_kind' {merged['topics_kind']!r} is not one of the kinds")
        self.topics_folder = self.by_tag[merged["topics_kind"]].folder

        self.statuses = _str_list(merged, "statuses")
        self.compiled_fields = _str_list(merged, "compiled_fields")
        for k in kinds:
            clash = sorted({f.name for f in k.fields} & ({"tags"} | set(self.compiled_fields)))
            if clash:
                raise ConfigError(f"kind '{k.tag}': fields {', '.join(clash)} are core fields and can't be redefined")

        if not isinstance(merged["source_fields"], dict) or not merged["source_fields"]:
            raise ConfigError("'source_fields' must be a non-empty object")
        self.source_fields = tuple(parse_field_spec(n, spec, "source_fields")
                                   for n, spec in merged["source_fields"].items())
        by_name = {f.name: f for f in self.source_fields}
        for name, ftype in CORE_SOURCE_FIELDS.items():
            if name not in by_name or by_name[name].type != ftype:
                raise ConfigError(f"source_fields must define '{name}' with type {ftype} (the core relies on it)")
        self.source_required = tuple(f.name for f in self.source_fields if f.required is True)
        self.source_recommended = tuple(f.name for f in self.source_fields if f.required == "recommended")

        for f in [*self.source_fields, *(f for k in kinds for f in k.fields)]:
            targets = [f.to_kind] if f.to_kind else []
            for t in targets:
                if t != "source" and t not in self.by_tag:
                    raise ConfigError(f"field '{f.name}': to_kind {t!r} is not 'source' or a kind tag")
        self.placeholders = _str_list(merged, "placeholders")
        try:
            self.raw_name_re = re.compile(merged["raw_name_pattern"])
        except (re.error, TypeError) as e:
            raise ConfigError(f"'raw_name_pattern' is not a valid regex: {e}") from None
        if not isinstance(merged["rules"], list):
            raise ConfigError("'rules' must be a list")
        default_kinds = tuple(k.tag for k in kinds if k.requires_sources)
        self.rules = tuple(parse_rule(r, i, self, default_kinds) for i, r in enumerate(merged["rules"]))
        ids = [r.id for r in self.rules]
        dup = sorted({x for x in ids if ids.count(x) > 1})
        if dup:
            raise ConfigError(f"duplicate rule id(s): {', '.join(dup)}")
        self.required_dirs = ("Raw/Sources", "Raw/Files", *(f"Wiki/{k.folder}" for k in kinds),
                              *_str_list(merged, "extra_required_dirs"))
        self.generated_files = {CATALOG, WIKI_INDEX, *(folder_index(k.folder) for k in kinds)}
        self.system_files = self.generated_files | {WIKI_LOG}

        if not isinstance(merged["generators"], list):
            raise ConfigError("'generators' must be a list")
        self.generators = tuple(parse_generator(g, i, self) for i, g in enumerate(merged["generators"]))
        for attr in ("id", "output"):
            values = [getattr(g, attr) for g in self.generators]
            dup = sorted({x for x in values if values.count(x) > 1})
            if dup:
                raise ConfigError(f"duplicate generator {attr}(s): {', '.join(dup)}")
        self.generator_outputs = tuple(g.output for g in self.generators)
        # Outputs outside kind folders are system files (not notes); inside a kind folder they are notes.
        loose = {g.output for g in self.generators if generator_kind(self, g.output) is None}
        self.generated_files |= loose
        self.system_files |= loose

    @classmethod
    def load(cls, root: Path) -> "Config":
        path = root / CONFIG_FILE
        if not path.exists():
            return cls({}, "built-in defaults")
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as e:
            raise ConfigError(f"{CONFIG_FILE}: invalid JSON ({e.msg}, line {e.lineno})") from None
        if not isinstance(data, dict):
            raise ConfigError(f"{CONFIG_FILE}: must be a JSON object")
        try:
            return cls(data, CONFIG_FILE)
        except ConfigError as e:
            raise ConfigError(f"{CONFIG_FILE}: {e}") from None


@dataclass
class Profile:
    """Optional domain plugins from scripts/profiles/<name>/ (rules.py, generators.py, converters.py).

    rules.py       compiled_rules(v, add, core) and/or source_rules(v, add, core);
                   add(level, code, path, message, line=None) records a Finding.
    generators.py  generate(v, core) -> {vault-relative path under Wiki/: file content};
                   written by `build` and checked for staleness by `lint` (K1).
    converters.py  CONVERTERS = {name: fn(src: Path, out: Path, core) -> str}, run by `convert`.
    `core` is this module, so plugins can reuse its helpers (split_frontmatter, body_links, ...).
    """
    name: str
    path: Path | None
    modules: dict = field(default_factory=dict)

    @classmethod
    def load(cls, root: Path, name: str) -> "Profile":
        path = root / PROFILES_DIR / name
        if not path.is_dir():
            if name == "default":
                return cls(name, None)
            raise ConfigError(f"profile '{name}' not found at {PROFILES_DIR}/{name}/")
        prof = cls(name, path)
        for stem in ("rules", "generators", "converters"):
            file = path / f"{stem}.py"
            if not file.is_file():
                continue
            spec = importlib.util.spec_from_file_location(f"wiki_profile_{name}_{stem}", file)
            module = importlib.util.module_from_spec(spec)
            try:
                spec.loader.exec_module(module)
            except Exception as e:  # a broken plugin must not crash silently
                raise ConfigError(f"profile '{name}': cannot load {stem}.py: {type(e).__name__}: {e}") from None
            prof.modules[stem] = module
        return prof

    def hook(self, module: str, name: str):
        return getattr(self.modules.get(module), name, None)

    def converters(self) -> dict:
        found = getattr(self.modules.get("converters"), "CONVERTERS", None) or {}
        return dict(found) if isinstance(found, dict) else {}

    def describe(self) -> str:
        hooks = [f"{m}.{fn}" for m, fn in (("rules", "compiled_rules"), ("rules", "source_rules"),
                                            ("generators", "generate")) if self.hook(m, fn)]
        conv = sorted(self.converters())
        if conv:
            hooks.append(f"converters: {', '.join(conv)}")
        where = f"{PROFILES_DIR}/{self.name}/" if self.path else "built in"
        return f"profile '{self.name}' ({where}): " + (", ".join(hooks) if hooks else "no plugins")



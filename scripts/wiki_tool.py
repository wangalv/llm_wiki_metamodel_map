RULE_COMMON_KEYS = {"id", "type", "level", "message", "description"}
RULE_PARAMS = {
    "anchor_required": {"kinds", "sources"},
    "alias_matches_anchor": {"kinds", "alias", "anchor"},
    "coverage": {"by_kinds", "where", "sources", "processed_only", "heading", "levels", "exclude", "text"},
    "rows_cited": {"kinds", "require_anchor", "under_heading"},
    "quote_matches": {"kinds", "callout"},
    "unique_scope": {"kinds", "fields"},
    "filename": {"kinds", "pattern"},
}
RULE_REQUIRED = {
    "alias_matches_anchor": {"alias", "anchor"},
    "coverage": {"by_kinds", "heading"},
    "unique_scope": {"fields"},
    "filename": {"pattern"},
}
RULE_DEFAULT_MESSAGES = {
    "anchor_required": "citation must point at a heading or block of the source",
    "alias_matches_anchor": "citation label does not match its anchor",
    "coverage": "not cited by any note",
    "rows_cited": "table row has no source citation",
    "quote_matches": "quote does not match the cited source",
    "unique_scope": "another note has the same values",
    "filename": "filename does not match the required pattern",
}
CORE_CODE_RE = re.compile(r"^[FSLNCKM]\d+$")


@dataclass(frozen=True)
class Rule:
    id: str
    type: str
    level: str
    message: str
    description: str
    params: dict


def _rule_regex(raw: dict, key: str, where: str, groups: int | None = None):
    value = raw.get(key)
    if value is None:
        return None
    if not isinstance(value, str):
        raise ConfigError(f"{where}: '{key}' must be a regex string")
    try:
        rx = re.compile(value)
    except re.error as e:
        raise ConfigError(f"{where}: '{key}' is not a valid regex: {e}") from None
    if groups is not None and rx.groups != groups:
        raise ConfigError(f"{where}: '{key}' must have exactly {groups} capture group")
    return rx


def parse_rule(raw, i: int, cfg: "Config", default_kinds: tuple[str, ...]) -> Rule:
    where = f"rules[{i}]"
    if not isinstance(raw, dict):
        raise ConfigError(f"{where}: must be an object")
    rtype = raw.get("type")
    if rtype not in RULE_PARAMS:
        raise ConfigError(f"{where}: 'type' must be one of {', '.join(sorted(RULE_PARAMS))}")
    bad = sorted(set(raw) - RULE_COMMON_KEYS - RULE_PARAMS[rtype])
    if bad:
        raise ConfigError(f"{where} ({rtype}): unknown key(s): {', '.join(bad)}")
    missing = sorted(RULE_REQUIRED.get(rtype, set()) - set(raw))
    if missing:
        raise ConfigError(f"{where} ({rtype}): missing key(s): {', '.join(missing)}")
    rid = raw.get("id")
    if not isinstance(rid, str) or not re.fullmatch(r"[A-Z][A-Z0-9_-]{0,11}", rid) or CORE_CODE_RE.match(rid):
        raise ConfigError(f"{where}: 'id' must be an uppercase code like 'LG1' that is not a core code (F1, S2, …)")
    level = raw.get("level", "error")
    if level not in ("error", "warn"):
        raise ConfigError(f"{where}: 'level' must be 'error' or 'warn'")
    where = f"{where} ({rid})"

    def kinds_param(key: str, default: tuple[str, ...]) -> tuple[str, ...]:
        value = raw.get(key, list(default))
        if not isinstance(value, list) or not value or not all(isinstance(x, str) for x in value):
            raise ConfigError(f"{where}: '{key}' must be a non-empty list of kind tags")
        unknown = sorted(set(value) - set(cfg.by_tag))
        if unknown:
            raise ConfigError(f"{where}: unknown kind(s) in '{key}': {', '.join(unknown)}")
        return tuple(value)

    params: dict = {}
    if rtype != "coverage":
        params["kinds"] = kinds_param("kinds", default_kinds if rtype == "anchor_required" else tuple(cfg.by_tag))
    if rtype == "anchor_required":
        params["sources"] = _rule_regex(raw, "sources", where)
    elif rtype == "alias_matches_anchor":
        params["alias"] = _rule_regex(raw, "alias", where, groups=1)
        params["anchor"] = _rule_regex(raw, "anchor", where, groups=1)
    elif rtype == "coverage":
        params["by_kinds"] = kinds_param("by_kinds", ())
        where_fields = raw.get("where", {})
        if not isinstance(where_fields, dict) or not all(isinstance(k, str) for k in where_fields):
            raise ConfigError(f"{where}: 'where' must be an object of field: value")
        params["where"] = dict(where_fields)
        params["sources"] = _rule_regex(raw, "sources", where)
        params["heading"] = _rule_regex(raw, "heading", where)
        params["exclude"] = _rule_regex(raw, "exclude", where)
        params["text"] = _rule_regex(raw, "text", where)
        levels = raw.get("levels", [1, 6])
        if (not isinstance(levels, list) or len(levels) != 2 or not all(isinstance(x, int) for x in levels)
                or not 1 <= levels[0] <= levels[1] <= 6):
            raise ConfigError(f"{where}: 'levels' must be [min, max] with 1 <= min <= max <= 6")
        params["levels"] = tuple(levels)
        processed_only = raw.get("processed_only", True)
        if not isinstance(processed_only, bool):
            raise ConfigError(f"{where}: 'processed_only' must be true or false")
        params["processed_only"] = processed_only
    elif rtype == "rows_cited":
        require_anchor = raw.get("require_anchor", True)
        if not isinstance(require_anchor, bool):
            raise ConfigError(f"{where}: 'require_anchor' must be true or false")
        params["require_anchor"] = require_anchor
        params["under_heading"] = _rule_regex(raw, "under_heading", where)
    elif rtype == "quote_matches":
        callout = raw.get("callout", "quote")
        if not isinstance(callout, str) or not re.fullmatch(r"[a-z][a-z0-9-]*", callout):
            raise ConfigError(f"{where}: 'callout' must be a callout type like 'quote'")
        params["callout"] = callout
    elif rtype == "unique_scope":
        fields = raw.get("fields")
        known = set(cfg.compiled_fields) | {f.name for k in cfg.kinds for f in k.fields}
        if not isinstance(fields, list) or not fields or not all(isinstance(x, str) for x in fields):
            raise ConfigError(f"{where}: 'fields' must be a non-empty list of field names")
        unknown = sorted(set(fields) - known)
        if unknown:
            raise ConfigError(f"{where}: unknown field(s): {', '.join(unknown)}")
        params["fields"] = tuple(fields)
    elif rtype == "filename":
        params["pattern"] = _rule_regex(raw, "pattern", where)
    message = raw.get("message", RULE_DEFAULT_MESSAGES[rtype])
    if not isinstance(message, str) or not message:
        raise ConfigError(f"{where}: 'message' must be a non-empty string")
    return Rule(rid, rtype, level, message, str(raw.get("description", "")), params)


# --- helpers shared by the rule types --------------------------------------

LEVEL_HEADING_RE = re.compile(r"^(#{1,6})[ \t]+(.+?)[ \t]*#*[ \t]*$")


@dataclass
class Section:
    line: int        # 1-based line of the heading in the file
    level: int
    title: str
    text: str        # the heading's content, up to the next heading of the same or a higher level


def norm_heading(text: str) -> str:
    return " ".join(text.split()).casefold()


def source_sections(note: Note) -> list[Section]:
    """Headings of a note's body with their section text (code blocks and comments ignored)."""
    lines = note.body.split("\n")
    masked = mask_code(note.body).split("\n")
    heads = [(i, len(m.group(1)), m.group(2)) for i, line in enumerate(masked)
             if (m := LEVEL_HEADING_RE.match(line))]
    out = []
    for n, (i, level, title) in enumerate(heads):
        end = next((j for j, lv, _ in heads[n + 1:] if lv <= level), len(lines))
        out.append(Section(note.body_line + i, level, title, "\n".join(lines[i + 1:end])))
    return out


def block_text(text: str, block_id: str) -> str | None:
    """The paragraph carrying an Obsidian block id ^block_id, without the id."""
    paras = re.split(r"\n\s*\n", text)
    for para in paras:
        if re.search(rf"(^|\s)\^{re.escape(block_id)}\s*$", para, re.M):
            return re.sub(rf"\s*\^{re.escape(block_id)}\s*$", "", para, flags=re.M)
    return None


def norm_quote(text: str) -> str:
    """Compare text ignoring Markdown formatting, list/quote markers, links and whitespace."""
    text = WIKILINK_RE.sub(lambda m: (m.group(3) or m.group(2).partition("#")[0]), text)
    text = re.sub(r"(?m)^\s*(?:>\s?)*(?:[-*+]\s+|\d+[.)]\s+)?", "", text)
    text = re.sub(r"[*_`]", "", text).replace("\\|", "|")
    return " ".join(text.split())


def note_citations(v: "Vault", note: Note) -> list[tuple[Link, str]]:
    """Body links of a note that resolve to Raw sources, with the resolved source path."""
    sources = set(v.source_paths())
    out = []
    for link in body_links(note.body, note.body_line):
        r = v.resolve(link.target)
        if r in sources:
            out.append((link, r))
    return out


def _anchor_key(anchor: str) -> str:
    return norm_heading(anchor.split("#")[-1])


def _field_key(v: "Vault", value):
    if isinstance(value, list):
        return tuple(_field_key(v, x) for x in value)
    if isinstance(value, str) and WIKILINK_RE.search(value):
        target = link_target(value)
        return v.resolve(target) or target
    return value


# --- the rule types --------------------------------------------------------

def _notes_of(v: "Vault", kinds) -> list[Note]:
    notes = [v.note(p) for p in v.compiled_paths()]
    return [n for n in notes if n.fm is not None and n.folder_tag in kinds]


def rule_anchor_required(v, rule, emit):
    rx = rule.params["sources"]
    for n in _notes_of(v, rule.params["kinds"]):
        for link, src in note_citations(v, n):
            if rx and not rx.search(src):
                continue
            if not link.anchor:
                emit(n.path, f"[[{link.target}]] cites the whole source", link.line)


def rule_alias_matches_anchor(v, rule, emit):
    alias_rx, anchor_rx = rule.params["alias"], rule.params["anchor"]
    for n in _notes_of(v, rule.params["kinds"]):
        for link, _ in note_citations(v, n):
            m = alias_rx.search(link.alias or "")
            if not m or link.anchor.startswith("^"):  # block ids carry no number to compare
                continue
            a = anchor_rx.search(link.anchor.split("#")[-1].strip()) if link.anchor else None
            if not a or a.group(1).casefold() != m.group(1).casefold():
                shown = f"#{link.anchor}" if link.anchor else "no anchor"
                emit(n.path, f"label '{link.alias}' vs {shown}", link.line)


def rule_coverage(v, rule, emit):
    p = rule.params
    cited: dict[str, set[str]] = {}
    for n in _notes_of(v, p["by_kinds"]):
        fm = n.fm or {}
        if any(str(fm.get(k)) != str(val) for k, val in p["where"].items()):
            continue
        for link, src in note_citations(v, n):
            if link.anchor:
                cited.setdefault(src, set()).add(_anchor_key(link.anchor))
    lo, hi = p["levels"]
    for src in v.source_paths():
        note = v.note(src)
        if p["sources"] and not p["sources"].search(src):
            continue
        if p["processed_only"] and (note.fm or {}).get("Processed") is not True:
            continue
        for sec in source_sections(note):
            if not lo <= sec.level <= hi or not p["heading"].search(sec.title):
                continue
            if p["exclude"] and p["exclude"].search(sec.title):
                continue
            if p["text"] and not p["text"].search(sec.text):
                continue
            if norm_heading(sec.title) not in cited.get(src, set()):
                emit(src, f"'{sec.title}' (kinds: {', '.join(p['by_kinds'])})", sec.line)


def rule_rows_cited(v, rule, emit):
    under = rule.params["under_heading"]
    for n in _notes_of(v, rule.params["kinds"]):
        sources = set(v.source_paths())
        lines = mask_code(n.body).split("\n")
        heading, in_table, row = "", False, 0
        for i, line in enumerate(lines):
            m = LEVEL_HEADING_RE.match(line)
            if m:
                heading = m.group(2)
            is_row = line.lstrip().startswith("|")
            if not is_row:
                in_table, row = False, 0
                continue
            row += 1
            if row == 1:  # header row
                continue
            if row == 2 and re.fullmatch(r"\s*\|?[\s:|-]+\|?\s*", line):  # separator
                in_table = True
                continue
            if not in_table or (under and not under.search(heading)):
                continue
            ok = False
            for link in body_links(line, 0):
                if v.resolve(link.target) in sources and (link.anchor or not rule.params["require_anchor"]):
                    ok = True
                    break
            if not ok:
                cells = [c.strip() for c in line.strip().strip("|").split("|")]
                emit(n.path, f"row '{cells[0][:40]}'", n.body_line + i)


def rule_quote_matches(v, rule, emit):
    head_rx = re.compile(rf"^>\s*\[!{re.escape(rule.params['callout'])}\][-+]?(.*)$", re.I)
    source_set = set(v.source_paths())
    scopes: dict[tuple[str, str], str] = {}  # (source, anchor) -> normalised text, computed once
    for n in _notes_of(v, rule.params["kinds"]):
        lines = n.body.split("\n")
        i = 0
        while i < len(lines):
            m = head_rx.match(lines[i])
            if not m:
                i += 1
                continue
            start, header, body = i, m.group(1), []
            i += 1
            while i < len(lines) and lines[i].startswith(">"):
                body.append(re.sub(r"^>\s?", "", lines[i]))
                i += 1
            chunk = header + "\n" + "\n".join(body)
            cites = [(l, r) for l, r in ((l, v.resolve(l.target)) for l in body_links(chunk, 0))
                     if r in source_set]
            line_no = n.body_line + start
            if not cites:
                emit(n.path, "quote has no source citation", line_no)
                continue
            link, src = cites[0]
            if (src, link.anchor) not in scopes:
                src_note = v.note(src)
                if link.anchor.startswith("^"):
                    scope = block_text(src_note.body, link.anchor[1:]) or ""
                elif link.anchor:
                    key = _anchor_key(link.anchor)
                    scope = next((s.text for s in source_sections(src_note) if norm_heading(s.title) == key), "")
                else:
                    scope = src_note.body
                scopes[(src, link.anchor)] = norm_quote(scope)
            quote = norm_quote(WIKILINK_RE.sub(
                lambda mm: "" if v.resolve(mm.group(2).partition("#")[0].strip()) in source_set
                else mm.group(0), "\n".join(body)))
            if not quote:
                emit(n.path, "quote is empty", line_no)
            elif quote not in scopes[(src, link.anchor)]:
                shown = f"#{link.anchor}" if link.anchor else "the source"
                emit(n.path, f"'{quote[:60]}' not found in {Path(src).stem} {shown}", line_no)


def rule_unique_scope(v, rule, emit):
    seen: dict[tuple, list[str]] = {}
    for n in _notes_of(v, rule.params["kinds"]):
        fm = n.fm or {}
        values = [fm.get(f) for f in rule.params["fields"]]
        if any(x is None for x in values):
            continue
        seen.setdefault(tuple(_field_key(v, x) for x in values), []).append(n.path)
    for paths in seen.values():
        for p in sorted(paths)[1:]:
            emit(p, f"same {', '.join(rule.params['fields'])} as {sorted(paths)[0]}")


def rule_filename(v, rule, emit):
    rx = rule.params["pattern"]
    for n in _notes_of(v, rule.params["kinds"]):
        if not rx.search(n.title):
            emit(n.path, f"'{n.title}' does not match {rx.pattern!r}")


RULE_RUNNERS = {
    "anchor_required": rule_anchor_required,
    "alias_matches_anchor": rule_alias_matches_anchor,
    "coverage": rule_coverage,
    "rows_cited": rule_rows_cited,
    "quote_matches": rule_quote_matches,
    "unique_scope": rule_unique_scope,
    "filename": rule_filename,
}


def run_config_rules(v: "Vault", add) -> None:
    """Run the declarative rules from wiki-config.json."""
    for rule in v.cfg.rules:
        def emit(path, detail, line=None, rule=rule):
            add(rule.level, rule.id, path, f"{rule.message}: {detail}" if detail else rule.message, line)
        RULE_RUNNERS[rule.type](v, rule, emit)


def git_ignored(v: Vault, rels: list[str]) -> list[str]:
    """Vault-relative paths that git would ignore (empty if git or a repo is unavailable)."""
    if not rels:
        return []
    try:
        out = subprocess.run(["git", "-C", str(v.root), "check-ignore", "--no-index", "--stdin", "-z"],
                             input="\0".join(rels) + "\0", capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return []
    if out.returncode not in (0, 1):  # 128: not a git repository
        return []
    return sorted(p for p in out.stdout.split("\0") if p)



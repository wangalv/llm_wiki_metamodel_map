WIKILINK_RE = re.compile(r"(!?)\[\[([^\[\]|]*)(?:\|([^\[\]]*))?\]\]")
MASK_RES = (
    re.compile(r"(?ms)^[ \t]*(`{3,}|~{3,})[^\n]*\n.*?^[ \t]*\1[ \t]*$"),  # fenced code
    re.compile(r"<!--.*?-->", re.S),                                   # HTML comments
    re.compile(r"%%.*?%%", re.S),                                       # Obsidian comments
    re.compile(r"`[^`\n]*`"),                                           # inline code
)
HEADING_RE = re.compile(r"^#{1,6}[ \t]+(.+?)[ \t]*#*[ \t]*$", re.M)


def mask_code(text: str) -> str:
    """Blank out code and comments, keeping newlines so line numbers still match."""
    for rx in MASK_RES:
        text = rx.sub(lambda m: re.sub(r"[^\n]", " ", m.group(0)), text)
    return text


@dataclass
class Link:
    target: str
    anchor: str
    line: int
    alias: str = ""  # display text after "|", if any


def body_links(body: str, first_line: int) -> list[Link]:
    masked = mask_code(body)
    links = []
    for m in WIKILINK_RE.finditer(masked):
        # Inside Markdown tables the alias pipe is escaped as "\|"; drop the backslash.
        target, _, anchor = m.group(2).rstrip("\\").partition("#")
        if target.strip():
            links.append(Link(target.strip(), anchor.strip(), first_line + masked.count("\n", 0, m.start()),
                              (m.group(3) or "").strip()))
    return links


def link_target(item) -> str | None:
    """Target of a frontmatter entry like "[[Note#Heading|alias]]" (or a bare name)."""
    if not isinstance(item, str) or not item.strip():
        return None
    m = WIKILINK_RE.search(item)
    target = m.group(2) if m else item
    return target.partition("#")[0].strip() or None


def summarize(body: str) -> str:
    """First sentence of the first plain paragraph after the H1."""
    for line in mask_code(body).split("\n"):
        s = line.strip()
        if not s or s.startswith("# "):
            continue
        if s.startswith(("#", ">", "|", "-", "*", "+", "!", "<")) or re.match(r"\d+[.)]\s", s):
            return ""
        s = re.sub(r"\s*\((?:\[\[[^\]]*\]\][,;\s]*)+\)", "", s)  # drop citation groups
        s = WIKILINK_RE.sub(lambda m: (m.group(3) or m.group(2).partition("#")[0]).strip(), s)
        return re.split(r"(?<=[.!?])\s+", s, maxsplit=1)[0].strip()
    return ""


def headings(text: str) -> set[str]:
    return {" ".join(h.split()).casefold() for h in HEADING_RE.findall(mask_code(text))}


def is_date(value) -> bool:
    if not isinstance(value, str) or not DATE_RE.match(value):
        return False
    try:
        dt.date.fromisoformat(value)
        return True
    except ValueError:
        return False


def today() -> str:
    return dt.date.today().isoformat()



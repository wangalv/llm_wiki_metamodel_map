@dataclass
class Finding:
    level: str  # "error" | "warn"
    code: str
    path: str
    message: str
    line: int | None = None


def report(findings: list[Finding], name: str, strict: bool = False) -> int:
    findings.sort(key=lambda f: (f.level != "error", f.path, f.line or 0, f.code))
    for f in findings:
        loc = f"{f.path}:{f.line}" if f.line else f.path
        print(f"{f.level.upper():5} {f.code:3} {loc}: {f.message}")
    errors = sum(f.level == "error" for f in findings)
    warns = len(findings) - errors
    print(f"{name}: {errors} error(s), {warns} warning(s)")
    return 1 if errors or (strict and warns) else 0



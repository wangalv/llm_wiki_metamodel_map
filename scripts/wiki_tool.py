def catalog_entry(v: Vault, note: Note) -> dict:
    fm = note.fm or {}
    compiled = set(v.compiled_paths())
    links = sorted({
        r for r in (v.resolve(link.target) for link in body_links(note.body, note.body_line))
        if r in compiled and r != note.path
    })
    entry = {
        "path": note.path,
        "title": note.title,
        "tag": single_tag(note, v.cfg.allowed_tags),
        "summary": summarize(note.body),
        "topics": v.fm_link_paths(note, "topics"),
        "sources": v.fm_link_paths(note, "sources"),
        "source_count": fm.get("source_count"),
        "aliases": [str(a) for a in as_list(fm.get("aliases")) if a is not None],
        "status": fm.get("status"),
        "links": links,
        "updated": str(fm.get("updated") or ""),
    }
    if note.kind and note.kind.fields:
        entry["fields"] = {f.name: field_catalog_value(v, f, fm.get(f.name)) for f in note.kind.fields}
    return entry


def _link(path: str, label: str, in_table: bool = False) -> str:
    """Path-qualified wikilink; the alias pipe is escaped inside Markdown tables."""
    pipe = "\\|" if in_table else "|"
    return "[[" + path[:-3] + pipe + label + "]]"


def _cell(text) -> str:
    return str(text if text is not None else "").replace("|", "\\|").replace("\n", " ")


def profile_outputs(v: Vault) -> dict[str, str]:
    """Files produced by the profile's generators.generate(v, core); only under Wiki/."""
    generate = v.profile.hook("generators", "generate")
    if not generate:
        return {}
    outputs = generate(v, sys.modules[__name__]) or {}
    for rel, content in outputs.items():
        if not isinstance(rel, str) or not rel.startswith("Wiki/") or ".." in rel.split("/") \
                or rel in v.cfg.system_files or not isinstance(content, str):
            raise ConfigError(f"profile '{v.profile.name}': generator returned an invalid output {rel!r}")
    return dict(sorted(outputs.items()))


def render_outputs(v: Vault) -> dict[str, str]:
    entries = [catalog_entry(v, v.note(p)) for p in v.compiled_paths()]
    outputs = {CATALOG: "".join(json.dumps(e, ensure_ascii=False) + "\n" for e in entries)}
    folders = [k.folder for k in v.cfg.kinds]

    by_folder = {d: [e for e in entries if e["path"].split("/")[1] == d] for d in folders}
    for k in v.cfg.kinds:
        if k.index_order == "desc":
            by_folder[k.folder].sort(key=lambda e: e["path"], reverse=True)

    idx = ["# Wiki Index", "", GENERATED_NOTICE, "",
           f"{len(entries)} compiled notes. Machine-readable catalog: `{CATALOG}`. Activity log: `{WIKI_LOG}`.", "",
           "| Section | Notes |", "|---|---:|"]
    idx += [f"| {_link(folder_index(d), d, in_table=True)} | {len(by_folder[d])} |" for d in folders]
    for d in folders:
        idx += ["", f"## {d}", ""]
        idx += [f"- {_link(e['path'], e['title'])}" + (f" — {e['summary']}" if e["summary"] else "")
                for e in by_folder[d]] or ["_No notes yet._"]
    outputs[WIKI_INDEX] = "\n".join(idx) + "\n"

    for d in folders:
        rows = by_folder[d]
        page = [f"# {d} Index", "", GENERATED_NOTICE, "",
                f"{_link(WIKI_INDEX, 'Wiki Index')} · {len(rows)} notes", ""]
        if rows:
            page += ["| Note | Status | Sources | Updated | Summary |", "|---|---|---:|---|---|"]
            page += [f"| {_link(e['path'], e['title'], in_table=True)} | {_cell(e['status'])} | "
                     f"{_cell(e['source_count'])} | {_cell(e['updated'])} | {_cell(e['summary'])} |" for e in rows]
        else:
            page.append("_No notes yet._")
        outputs[folder_index(d)] = "\n".join(page) + "\n"
    return outputs


def generated_phase(v: Vault, phase: str) -> dict[str, str]:
    """Generator outputs for a build phase: 'sources' (config generators except catalog_table, plus
    profile plugins) or 'notes' (catalog_table, which reads notes written by the first phase)."""
    outputs = config_generator_outputs(v, phase)
    if phase == "sources":
        plugin = profile_outputs(v)
        clash = sorted(set(plugin) & set(outputs))
        if clash:
            raise ConfigError(f"profile generator and config generator both write {', '.join(clash)}")
        outputs.update(plugin)
    return outputs


def stale_outputs(v: Vault) -> list[str]:
    stale = []
    everything = {**generated_phase(v, "sources"), **generated_phase(v, "notes"), **render_outputs(v)}
    for rel, content in everything.items():
        path = v.abs(rel)
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(rel)
    return stale


def _write_outputs(v: Vault, outputs: dict[str, str]) -> int:
    written = 0
    for rel, content in outputs.items():
        path = v.abs(rel)
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written += 1
        print(f"wrote {rel}")
    return written


def cmd_build(v: Vault, args) -> int:
    # Generators run first: what they write (possibly notes) feeds the catalog.
    written = 0
    generated: dict[str, str] = {}
    for phase in ("sources", "notes"):
        outputs = generated_phase(v, phase)
        generated.update(outputs)
        n = _write_outputs(v, outputs)
        written += n
        if n:
            v.reset()
    for p in v.compiled_paths():
        if v.note(p).fm_error:
            print(f"warning: {p}: {v.note(p).fm_error} (run lint)", file=sys.stderr)
    outputs = render_outputs(v)
    written += _write_outputs(v, outputs)
    total = len(outputs) + len(generated)
    notes = len(v.compiled_paths())
    print(f"build: {notes} compiled notes; {written} file(s) written, {total - written} unchanged")
    return 0




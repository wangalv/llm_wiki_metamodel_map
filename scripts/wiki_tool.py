def main(argv: list[str] | None = None) -> int:
    if sys.version_info < MIN_PYTHON:
        print(f"wiki_tool.py needs Python >= {'.'.join(map(str, MIN_PYTHON))}", file=sys.stderr)
        return 1
    parser = argparse.ArgumentParser(prog="wiki_tool.py", description="Deterministic tooling for the LLM Wiki vault.")
    parser.add_argument("--root", type=Path, default=VAULT, help="vault root (default: parent of scripts/)")
    sub = parser.add_subparsers(dest="command", required=True, metavar="COMMAND")

    sub.add_parser("doctor", help="non-mutating health check").set_defaults(func=cmd_doctor)
    sub.add_parser("build", help="generate catalog.jsonl, index.md and folder indexes").set_defaults(func=cmd_build)

    p = sub.add_parser("lint", help="validate compiled Wiki notes")
    p.add_argument("--strict", action="store_true", help="fail on warnings too")
    p.set_defaults(func=cmd_lint)

    p = sub.add_parser("source-scan", help="list Raw sources; optionally update the source manifest")
    p.add_argument("--update", action="store_true", help=f"write {MANIFEST}")
    p.add_argument("--accept-covered", action="store_true",
                   help="with --update: mark covered sources processed (manifest and Processed frontmatter)")
    p.add_argument("--json", action="store_true", help="print manifest entries as JSON lines")
    p.set_defaults(func=cmd_source_scan)

    p = sub.add_parser("source-lint", help="validate source notes and coverage state")
    p.add_argument("--strict", action="store_true", help="fail on warnings too")
    p.set_defaults(func=cmd_source_lint)

    p = sub.add_parser("source-delta", help="show Raw sources not represented in the manifest")
    p.add_argument("--json", action="store_true")
    p.add_argument("--check", action="store_true", help="exit 1 if there is any delta")
    p.set_defaults(func=cmd_source_delta)

    p = sub.add_parser("source-coverage", help="show which Raw sources compiled notes cover")
    p.add_argument("--uncovered", action="store_true", help="only list uncovered sources")
    p.add_argument("--json", action="store_true")
    p.set_defaults(func=cmd_source_coverage)

    p = sub.add_parser("search-catalog", help="search compiled notes through the catalog")
    p.add_argument("--query", required=True)
    p.add_argument("--tag", help="only notes of this kind (see Schema/wiki-config.json)")
    p.add_argument("--limit", type=int, default=20)
    p.add_argument("--json", action="store_true")
    p.set_defaults(func=cmd_search_catalog)

    p = sub.add_parser("log", help=f"append an entry to {WIKI_LOG}")
    p.add_argument("--title", required=True)
    p.add_argument("--details", default="")
    p.set_defaults(func=cmd_log)

    p = sub.add_parser("sync-schema", help="regenerate template frontmatter and Schema/field-reference.md from config")
    p.add_argument("--check", action="store_true", help="only report files that are out of date (exit 1 if any)")
    p.set_defaults(func=cmd_sync_schema)

    p = sub.add_parser("convert", help="convert a raw document with a profile converter")
    p.add_argument("converter", nargs="?", help="converter name (see --list)")
    p.add_argument("input", nargs="?", type=Path, help="file to convert")
    p.add_argument("--output", type=Path, help="where to write the result (e.g. Raw/Sources/<name>.md)")
    p.add_argument("--force", action="store_true", help="overwrite an existing output file")
    p.add_argument("--list", action="store_true", help="list the converters of the active profile")
    p.set_defaults(func=cmd_convert)

    args = parser.parse_args(argv)
    try:
        vault = Vault(args.root.resolve())
        return args.func(vault, args)
    except ConfigError as e:
        print(f"wiki_tool.py: configuration error: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())

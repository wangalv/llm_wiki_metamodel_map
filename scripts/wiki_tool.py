def lint_sources(v: Vault) -> list[Finding]:
    out: list[Finding] = []
    add = lambda lvl, code, path, msg, line=None: out.append(Finding(lvl, code, path, msg, line))
    cfg = v.cfg
    cov = coverage(v)
    raw_files = set(v.raw_file_paths())
    embedded: set[str] = set()

    for sp in v.source_paths():
        n = v.note(sp)
        if n.fm_error:
            add("error", "F1", sp, n.fm_error)
            continue
        fm = n.fm or {}
        missing = [k for k in cfg.source_required if k not in fm]
        if missing:
            add("error", "F2", sp, f"missing field(s): {', '.join(missing)}")
        absent = [k for k in cfg.source_recommended if k not in fm]
        if absent:
            add("warn", "F2", sp, f"missing recommended field(s): {', '.join(absent)}")
        if "tags" in fm and "source" not in as_list(fm.get("tags")):
            add("error", "F3", sp, "tags must include 'source'")
        if "Created" in fm and not is_date(fm.get("Created")):
            add("error", "F5", sp, f"Created must be YYYY-MM-DD, got {fm.get('Created')!r}")
        processed = fm.get("Processed")
        if "Processed" in fm and not isinstance(processed, bool):
            add("error", "F6", sp, f"Processed must be true or false, got {processed!r}")
        if "Title" in fm and not str(fm.get("Title") or "").strip():
            add("warn", "F2", sp, "Title is empty")
        for spec in cfg.source_fields:
            if spec.name not in CORE_SOURCE_CHECKED:
                for err in field_errors(v, spec, fm.get(spec.name)):
                    add("error", "F9", sp, f"field '{spec.name}': {err}")

        if processed is True and not cov[sp]:
            add("error", "S9", sp, "marked Processed: true but no compiled Wiki note cites it")
        elif processed is False and cov[sp]:
            add("warn", "S9", sp, f"covered by {len(cov[sp])} note(s) but Processed is false "
                                  "(run source-scan --update --accept-covered)")
        if not cov[sp]:
            add("warn", "L4", sp, "not yet compiled into Wiki/ (no note cites it)")

        for link in body_links(n.body, n.body_line):
            r = v.resolve(link.target)
            if r and r in raw_files:
                embedded.add(r)
            elif r is None and "." in Path(link.target).name:
                add("error", "S6", sp, f"attachment [[{link.target}]] not found")

        if not cfg.raw_name_re.match(n.title):
            add("error", "N1", sp, "filename should be YYYY-MM-DD-kebab-slug.md")
        if any(ph in n.text for ph in cfg.placeholders):
            add("warn", "C2", sp, "template placeholder left in source note")

    for f in sorted(raw_files - embedded):
        add("warn", "S7", f, "attachment is not embedded in any source note")
    for f in sorted(raw_files):
        if not cfg.raw_name_re.match(Path(f).stem):
            add("error", "N1", f, "filename should be YYYY-MM-DD-kebab-slug.ext")
    for rel in git_ignored(v, [f for f in v.files() if f.startswith("Raw/")]):
        add("error", "K4", rel, "ignored by .gitignore, so it would never be committed")

    try:
        manifest = read_manifest(v)
    except ValueError as e:
        add("error", "M1", MANIFEST, str(e))
    else:
        if manifest is None:
            add("warn", "M1", MANIFEST, "missing; run source-scan --update")
        else:
            delta = manifest_delta(v)
            for kind, paths in delta.items():
                for p in paths:
                    add("warn", "M1", p, f"manifest out of date ({kind}); run source-scan --update")
    run_profile_rules(v, "source_rules", add)
    return out


def cmd_source_lint(v: Vault, args) -> int:
    return report(lint_sources(v), "source-lint", args.strict)


def cmd_source_delta(v: Vault, args) -> int:
    try:
        delta = manifest_delta(v)
    except ValueError as e:
        print(f"source-delta: {e}", file=sys.stderr)
        return 1
    if args.json:
        print(json.dumps(delta, ensure_ascii=False, indent=2))
    else:
        if read_manifest(v) is None:
            print(f"note: {MANIFEST} does not exist yet; every source counts as new")
        labels = {"new": "not in manifest", "removed": "in manifest but missing on disk", "changed": "changed since manifest"}
        for kind, paths in delta.items():
            print(f"{labels[kind]} ({len(paths)}):")
            for p in paths:
                print(f"  {p}")
    has_delta = any(delta.values())
    return 1 if args.check and has_delta else 0


def cmd_source_coverage(v: Vault, args) -> int:
    cov = coverage(v)
    rows = [(p, c) for p, c in cov.items() if not (args.uncovered and c)]
    if args.json:
        print(json.dumps({p: c for p, c in rows}, ensure_ascii=False, indent=2))
        return 0
    for p, c in rows:
        if c:
            print(f"covered by {len(c)}: {p}")
            for note in c:
                print(f"    {note}")
        else:
            print(f"UNCOVERED    {p}")
    covered = sum(bool(c) for c in cov.values())
    print(f"source-coverage: {covered}/{len(cov)} source(s) covered by compiled Wiki notes")
    return 0


